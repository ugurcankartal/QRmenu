def should_preserve_contact_value(value):
    if not value:
        return True
    stripped = value.strip()
    if stripped.startswith(("http://", "https://", "www.")):
        return True
    if stripped.startswith("+") or stripped.replace(" ", "").isdigit():
        return True
    if "@" in stripped and "." in stripped and " " not in stripped:
        return True
    return False


def should_preserve_link_text(text):
    if not text:
        return True
    stripped = text.strip()
    if stripped.startswith("@"):
        return True
    if stripped.startswith(("http://", "https://")):
        return True
    return False
